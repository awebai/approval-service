"""Generate the Go schema projection from the single Python-package data file."""

import argparse
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
# Generation reads the source package's pure schema projection, not runtime
# verifier state or a separately copied schema-composition implementation.
sys.path.insert(0, str(root / "src"))
from approval_service.schema_projection import load_wire_schema

schema = load_wire_schema(root / "src/approval_service/data")
raw = json.dumps(schema, sort_keys=True, separators=(",", ":"))
assert "`" not in raw
output = (
    "// Code generated by scripts/generate_format.py; DO NOT EDIT.\npackage verify\n\nconst schemaJSON = `"
    + raw
    + "`\n"
)
p = root / "verify/schema_generated.go"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not p.exists() or p.read_text() != output:
        raise SystemExit("generated format is stale")
else:
    p.write_text(output)
